def clean_element_symbol(value: object) -> str:
    text = str(value or "").strip()

    match = re.match(
        r"([A-Za-z]{1,2})",
        text,
    )

    if match is None:
        return "X"

    symbol = match.group(1)

    if len(symbol) == 1:
        return symbol.upper()

    return symbol[0].upper() + symbol[1:].lower()


def element_color(element: str) -> str:
    symbol = clean_element_symbol(element)

    return ELEMENT_COLORS.get(
        symbol,
        ELEMENT_COLORS["X"],
    )


def display_radius(element: str) -> float:
    symbol = clean_element_symbol(element)

    return float(
        DISPLAY_RADII.get(
            symbol,
            DISPLAY_RADII["X"],
        )
    )


def covalent_radius(element: str) -> float:
    symbol = clean_element_symbol(element)

    return float(
        COVALENT_RADII.get(
            symbol,
            COVALENT_RADII["X"],
        )
    )